import os

from Generate_tree import SKT_tree
from Model_GCN import GCN, GAT

import torch
import torch.nn as nn
from torch_geometric.data import Data, DataLoader

def train_SKT(train_array_all, test_array_all, train_epoch=100):
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    print(f"Using device: {device}")
    print('Training GCN for GSR')

    train_data_group, test_data_group = SKT_tree(train_array_all, test_array_all)

    # Load the data into batch
    train_loader = DataLoader(train_data_group, batch_size=256, shuffle=True)
    test_loader = DataLoader(test_data_group, batch_size=256, shuffle=True)

    # initialization gcn
    model = GCN(1, 32, 2).to(device)
    # model = GAT(1, 32, 2).to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=0.01)
    criterion = nn.CrossEntropyLoss()

    # training
    for epoch in range(train_epoch):
        model.train()
        total_loss = 0
        for batch in train_loader:
            batch = batch.to(device)  # 将批次数据移动到GPU

            optimizer.zero_grad()

            # forward
            out = model(batch.x, batch.edge_index)

            # only use leaf
            leaf_node_output = out[batch.train_mask]

            # loss
            loss = criterion(leaf_node_output, batch.y)
            loss.backward()
            optimizer.step()
            total_loss += loss.item()

        if epoch % 20 == 0:
            print(f"Epoch {epoch}, Loss: {total_loss}")
    print('Training GCN for BVP done!')
    return model

if __name__ == '__main__':
    log_file = '../Feature_wise_Normalization/log_data_normalization_IT06_knn.log'
    data_file = '../Feature_wise_Normalization/Pack_all_data.json'

    model = train_SKT(data_file, log_file)

    train_data_group, test_data_group = SKT_tree(data_file, log_file)
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    print(f"Using device: {device}")
    # Load the data into batch
    train_loader = DataLoader(train_data_group, batch_size=256, shuffle=True)
    test_loader = DataLoader(test_data_group, batch_size=256, shuffle=True)

    # test
    model.eval()
    correct = 0
    total = 0
    for batch in test_loader:
        batch = batch.to(device)  # using gpu
        with torch.no_grad():
            pred = model(batch.x, batch.edge_index)
            pred = pred[batch.train_mask].argmax(dim=1)
            correct += (pred == batch.y).sum().item()
            total += batch.y.size(0)
    accuracy = correct / total
    print(f"Test Accuracy: {accuracy * 100:.2f}%")
